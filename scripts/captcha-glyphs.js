function decodeCaptchaMarkup(markup) {
  const source = String(markup || '');
  const grouped = new Map();
  const re = /class="cg"[^>]*data-g="(\d+)"[^>]*data-r="(\d+)"[^>]*data-c="(\d+)"/g;
  let match = re.exec(source);
  while (match) {
    const index = Number(match[1]);
    const cells = grouped.get(index) || [];
    cells.push(`${match[2]}:${match[3]}`);
    grouped.set(index, cells);
    match = re.exec(source);
  }
  const indexes = Array.from(grouped.keys()).sort((a, b) => a - b);
  return indexes.map(index => {
    const cells = new Set(grouped.get(index) || []);
    const signature = [];
    for (let row = 0; row < 7; row += 1) {
      let line = '';
      for (let col = 0; col < 5; col += 1) {
        line += cells.has(`${row}:${col}`) ? '1' : '0';
      }
      signature.push(line);
    }
    const key = signature.join('|');
    const found = Object.keys(CAPTCHA_GLYPHS).find(ch => CAPTCHA_GLYPHS[ch].join('|') === key);
    return found || '';
  }).join('');
}

function decodeCaptchaFromSvg(payload) {
  const source = typeof payload === 'string' ? payload : String((payload && (payload.svg || payload.svgMarkup)) || '');
  let markup = source;
  const comma = source.indexOf(',');
  if (source.startsWith('data:') && comma >= 0) {
    try {
      markup = decodeURIComponent(source.slice(comma + 1));
    } catch (_) {
      markup = source;
    }
  }
  return decodeCaptchaMarkup(markup);
}

